/**
 * Convert numbers to Marathi words (e.g. 10500 -> "दहा हजार पाचशे रुपये फक्त")
 */
export function numberToMarathiWords(amount: number): string {
  if (amount === 0) return 'शून्य रुपये फक्त';
  if (isNaN(amount)) return '';

  const units = ['', 'एक', 'दोन', 'तीन', 'चार', 'पाच', 'सहा', 'सात', 'आठ', 'नऊ', 'दहा',
    'अकरा', 'बारा', 'तेरा', 'चौदा', 'पंधरा', 'सोळा', 'सतरा', 'अठरा', 'एकोणीस'];
  
  const tens: { [key: number]: string } = {
    20: 'वीस', 21: 'एकवीस', 22: 'बावीस', 23: 'तेवीस', 24: 'चोवीस', 25: 'पंचवीस',
    26: 'सव्वीस', 27: 'सत्तावीस', 28: 'अठ्ठावीस', 29: 'एकोणतीस', 30: 'तीस',
    31: 'एकतीस', 32: 'बत्तीस', 33: 'तेहेतीस', 34: 'चौतीस', 35: 'पस्तीस',
    36: 'छत्तीस', 37: 'सदतीस', 38: 'अडतीस', 39: 'एकोणचाळीस', 40: 'चाळीस',
    41: 'एक्केचाळीस', 42: 'बेचाळीस', 43: 'त्रेचाळीस', 44: 'चव्वेचाळीस', 45: 'पंचेचाळीस',
    46: 'शेहेचाळीस', 47: 'सत्तेचाळीस', 48: 'अठ्ठेचाळीस', 49: 'एकोणपन्नास', 50: 'पन्नास',
    51: 'एक्कावन्न', 52: 'बावन्न', 53: 'त्रेपन्न', 54: 'चौपन्न', 55: 'पंचावन्न',
    56: 'छप्पन्न', 57: 'सत्तावन्न', 58: 'अठ्ठावन्न', 59: 'एकोणसाठ', 60: 'साठ',
    61: 'एकसष्ठ', 62: 'पासष्ठ', 63: 'त्रेसष्ठ', 64: 'चौसष्ठ', 65: 'पासष्ठ',
    66: 'सहासष्ठ', 67: 'सदुसष्ठ', 68: 'अडुसष्ठ', 69: 'एकोणसत्तर', 70: 'सत्तर',
    71: 'एकाहत्तर', 72: 'बाहत्तर', 73: 'त्र्याहत्तर', 74: 'चौर्‍याहत्तर', 75: 'पंच्याहत्तर',
    76: 'शहात्तर', 77: 'सत्त्याहत्तर', 78: 'अठ्ठ्याहत्तर', 79: 'एकोणऐंशी', 80: 'ऐंशी',
    81: 'एक्याऐंशी', 82: 'ब्याऐंशी', 83: 'त्र्याऐंशी', 84: 'चौऱ्याऐंशी', 85: 'पंच्याऐंशी',
    86: 'शहाऐंशी', 87: 'सत्त्याऐंशी', 88: 'अठ्ठ्याऐंशी', 89: 'एकोणनव्वद', 90: 'नव्वद',
    91: 'एक्याण्णव', 92: 'ब्याण्णव', 93: 'त्र्याण्णव', 94: 'चौऱ्याण्णव', 95: 'पंच्याण्णव',
    96: 'शहाण्णव', 97: 'सत्त्याण्णव', 98: 'अठ्ठाण्णव', 99: 'नव्व्याण्णव'
  };

  function getTwoDigitWord(num: number): string {
    if (num <= 0) return '';
    if (num < 20) return units[num];
    if (tens[num]) return tens[num];
    return num.toString();
  }

  let num = Math.floor(Math.abs(amount));
  let parts: string[] = [];

  const crores = Math.floor(num / 10000000);
  num %= 10000000;
  const lakhs = Math.floor(num / 100000);
  num %= 100000;
  const thousands = Math.floor(num / 1000);
  num %= 1000;
  const hundreds = Math.floor(num / 100);
  const remaining = num % 100;

  if (crores > 0) {
    parts.push(`${getTwoDigitWord(crores)} कोटी`);
  }
  if (lakhs > 0) {
    parts.push(`${getTwoDigitWord(lakhs)} लाख`);
  }
  if (thousands > 0) {
    parts.push(`${getTwoDigitWord(thousands)} हजार`);
  }
  if (hundreds > 0) {
    parts.push(`${units[hundreds]} शे`);
  }
  if (remaining > 0) {
    parts.push(getTwoDigitWord(remaining));
  }

  return `${parts.join(' ')} रुपये फक्त`;
}

/**
 * Format date in Marathi (e.g. "२८ ऑगस्ट २०२६")
 */
export function formatMarathiDate(dateString: string): string {
  if (!dateString) return '';
  const date = new Date(dateString);
  if (isNaN(date.getTime())) return dateString;

  const marathiMonths = [
    'जानेवारी', 'फेब्रुवारी', 'मार्च', 'एप्रिल', 'मे', 'जून',
    'जुलै', 'ऑगस्ट', 'सप्टेंबर', 'ऑक्टोबर', 'नोव्हेंबर', 'डिसेंबर'
  ];

  const day = date.getDate();
  const month = marathiMonths[date.getMonth()];
  const year = date.getFullYear();

  return `${day} ${month} ${year}`;
}

/**
 * Map payment method to Marathi
 */
export function getPaymentMethodMarathi(method: string): string {
  switch (method) {
    case 'Cash':
      return 'रोख (Cash)';
    case 'UPI':
      return 'युपीआय (UPI)';
    case 'Bank Transfer':
      return 'बँक ट्रान्सफर';
    case 'Cheque':
      return 'धनादेश (Cheque)';
    default:
      return method || 'इतर';
  }
}

